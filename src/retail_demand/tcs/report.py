from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from .. import config
from ..common.plot import AQUA, BLUE, GREY, ORANGE, barh, plt, save, style

LABELS = {"mean_28": "mean, last 28 days", "mean_56": "mean, last 56 days", "mean_112": "mean, last 112 days", "mean_7": "mean, last 7 days",
          "dow_mean_8": "same weekday, last 8 weeks", "tsb": "TSB estimate", "sba": "SBA estimate", "croston": "Croston estimate",
          "dow": "day of week", "price_rel": "price vs usual price", "price": "price", "price_rel_dept": "price vs department",
          "zero_share_28": "share of zero days, last 28", "zero_share_112": "share of zero days, last 112", "size_112": "average sale size",
          "interval_112": "average days between sales", "days_since_sale": "days since last sale", "std_28": "volatility, last 28 days",
          "product_code": "product", "outlet": "outlet", "h": "days ahead", "month": "month", "dom": "day of month", "woy_sin": "season (sine)",
          "woy_cos": "season (cosine)", "price_change": "price change vs last week", "department_identifier": "department",
          "category_code": "category", "state_code": "state"}


def _load(res: Path, name):
    return json.loads((res / f"{name}.json").read_text())


def figures(res: Path, fig: Path):
    v1, sc, dec, ex, eda = (_load(res, n) for n in ("v1", "screen", "decision", "explain", "eda"))
    # v1: random vs time split
    cats = list(v1["categories"])
    f, ax = plt.subplots(figsize=(7, 2.8))
    x = range(len(cats))
    ax.bar([i - 0.2 for i in x], [v1["categories"][k]["random_split"]["r2_test"] for k in cats], width=0.4, color=GREY, label="random 80/20 split (v1)")
    ax.bar([i + 0.2 for i in x], [v1["categories"][k]["time_split_last_8_weeks"]["r2_test"] for k in cats], width=0.4, color=ORANGE,
           label="time split: last 8 weeks")
    ax.axhline(0, color="#c9c8c3", lw=1)
    ax.set_xticks(list(x), [k.replace("_", " ").replace("fast moving consumer goods", "FMCG") for k in cats])
    ax.legend(frameon=False, fontsize=8)
    style(ax, "v1 design re-run: test R² of the same model under two splits", None, "R² (cube-root scale)")
    save(f, fig / "tcs_v1_split.png")
    # screen
    rows = sc["table"][::-1]
    f, ax = plt.subplots(figsize=(7, 0.32 * len(rows) + 1))
    barh(ax, [r["model"] for r in rows], [r["cv_rmse"] for r in rows], [GREY if r["baseline"] else BLUE for r in rows], fmt="{:.3f}")
    ax.set_xlim(2.5, max(r["cv_rmse"] for r in rows) * 1.08)
    style(ax, "Model screen: cross-validated RMSE, daily units (grey = baselines)", "RMSE")
    save(f, fig / "tcs_screen.png")
    # decision
    pol = dec["policies"]
    names = list(pol)[::-1]
    f, ax = plt.subplots(figsize=(7.5, 0.45 * len(names) + 1))
    barh(ax, names, [pol[n]["stock_vs_demand_at_95pct_fill_ex_post"] for n in names],
         [AQUA if n.startswith("Rule") else BLUE for n in names], fmt="{:.2f}x")
    style(ax, "Stock for a 95% fill rate, 8 test weeks", "order-up-to stock / demand")
    save(f, fig / "tcs_decision.png")
    # SHAP
    imp = pd.Series(ex["mean_abs_shap"]).head(12)[::-1]
    f, ax = plt.subplots(figsize=(6.5, 3.6))
    barh(ax, [LABELS.get(k, k) for k in imp.index], list(imp.values), [BLUE] * len(imp), fmt="{:.3f}")
    style(ax, "Mean |SHAP|, Poisson gradient boosting (log scale)", "mean absolute contribution")
    save(f, fig / "tcs_shap.png")


def markdown(res: Path) -> str:
    q, eda, v1, sc, tu, t, dec, ex, hyp = (_load(res, n) for n in ("quality", "eda", "v1", "screen", "tune", "test", "decision", "explain", "hypotheses"))
    c, a, cs = q["completeness"], q["accuracy"], q["consistency"]
    L = ["# Part A results: TCS iON retail project rebuilt (500 product × outlet series, weekly ordering)", "",
         "Generated by `python -m retail_demand.tcs.report` from `results/tcs/*.json`. Do not edit by hand.", "",
         "## Data checks", "", "| Dimension | Check | Result |", "|---|---|---|",
         f"| Validity | negative or fractional sales; non-positive prices | {q['validity']['negative_sales']}; {q['validity']['non_integer_sales']}; "
         f"{q['validity']['non_positive_prices']} (prices {q['validity']['price_min']:.2f} to {q['validity']['price_max']:.2f}) |",
         f"| Uniqueness | duplicate product-outlet-days | {q['uniqueness']['duplicate_product_outlet_date']} |",
         f"| Completeness | rows vs full grid | {c['rows']:,} of {c['grid_cells']:,}; every sale has a weekly price ({c['sales_rows_without_price']} missing) |",
         f"| Consistency | product→department→category, outlet→state | one-to-one ({cs['departments_per_product_max']}, {cs['categories_per_department_max']}, "
         f"{cs['states_per_outlet_max']}) |",
         f"| Consistency | price changes | {cs['price_changes_share_of_weeks']:.1%} of weeks: prices barely move, so price effects are weakly identified |",
         f"| Accuracy | prices below half / above double the series' usual price | {a['prices_below_half_series_median']} / "
         f"{a['prices_above_double_series_median']} weeks (kept as discounts) |",
         f"| Accuracy | long zero runs | {a['series_longest_zero_run_over_180_days']} series go > 180 days without a sale "
         f"(longest {a['longest_zero_run_days']} days): likely not stocked |",
         "| Relevance | demand classes (Syntetos-Boylan) | " + ", ".join(f"{k} {v}" for k, v in q["relevance"]["demand_classes"].items()) + " |", "",
         "## Exploratory analysis", "",
         f"- {c['zero_sales_share']:.0%} of product-outlet-days have zero sales; the median series sells {eda['series_mean_daily_sales_quantiles']['0.5']:.2f} units a day.",
         f"- The top 10% of series make {eda['top_10pct_series_share_of_sales']:.0%} of sales. Drinks & food: {eda['share_of_sales_by_category']['drinks_and_food']:.0%} of units.",
         f"- Weekends sell {eda['weekend_vs_weekday_ratio']:.2f}× weekdays.",
         f"- Discount weeks (price < 95% of usual) sell {eda['price_discount_effect_within_series']['median_log_diff']:+.1%} (log scale, median over "
         f"{eda['price_discount_effect_within_series']['series_with_discount_days']} series; {eda['price_discount_effect_within_series']['share_positive']:.0%} higher).", "",
         "## The original (v1) design, re-run", "", v1["design"] + ".", "",
         "| Category | Rows | R² train (random) | R² test (random 80/20) | R² test (time split, last 8 weeks) | MAE in units (time split) |", "|---|---|---|---|---|---|"]
    for k, v in v1["categories"].items():
        L.append(f"| {k} | {v['rows']:,} | {v['random_split']['r2_train']:.2f} | {v['random_split']['r2_test']:.3f} | {v['time_split_last_8_weeks']['r2_test']:.3f} | "
                 f"{v['time_split_last_8_weeks']['mae_units']:.2f} |")
    L += ["", "## Model screen (4 expanding-window folds of 8 weeks, development period)", "",
          "| Model | CV RMSE (SD) | CV MAE | CV WAPE | Bias | p vs best (Wilcoxon over series, Holm) |", "|---|---|---|---|---|---|"]
    for r in sc["table"]:
        p = r.get("vs_best", {}).get("p_holm")
        L.append(f"| {r['model']}{' (baseline)' if r['baseline'] else ''} | {r['cv_rmse']:.3f} ({r['cv_rmse_sd']:.3f}) | {r['cv_mae']:.3f} | {r['cv_wape']:.1%} | "
                 f"{r['cv_bias']:+.1%} | {'' if p is None else f'{p:.2g}'} |")
    L += ["", "Tuned: " + "; ".join(f"{x['model']} {x['cv_rmse']:.3f}" for x in tu["tuned"]) + f". Chosen: **{tu['model']}**.", "",
          f"## Test period ({t['window'][0]} to {t['window'][1]}, 8 weekly order dates, scored once)", "",
          "| Forecast | RMSE | MAE | WAPE | Bias | RMSE difference vs model (series bootstrap 95% CI) | Series where it is worse than the model (Wilcoxon p) |",
          "|---|---|---|---|---|---|---|"]
    for k, m in t["table"].items():
        d, w = m.get("rmse_diff_vs_model"), m.get("series_test_vs_model")
        L.append(f"| {k} | {m['rmse']:.3f} | {m['mae']:.3f} | {m['wape']:.1%} | {m['bias']:+.1%} | "
                 + (f"{d['value']:+.3f} ({d['ci'][0]:+.3f} to {d['ci'][1]:+.3f}) | {w['series_where_a_worse']:.0%} ({w['p']:.1g}) |" if d else "reference | |"))
    L += ["", "RMSE by demand class: " + "; ".join(f"{k}: model {v[t['model']]:.2f}, SBA {v['SBA (Syntetos-Boylan)']:.2f}, 28-day average "
                                                f"{v['Moving average, 28 days']:.2f} ({v['share_of_sales']:.0%} of sales)" for k, v in t["rmse_by_demand_class"].items()) + ".",
          "", f"## Weekly ordering decision (target fill rate {dec['fill_target']:.0%}, {dec['weeks']} test weeks, {dec['series']} series)", "",
          "Each policy's scale factor is set on the 8 weeks before the test period, then applied unchanged.", "",
          "| Policy | WAPE of weekly totals | Fill rate achieved | Stock / demand | Stock for 95% fill (ex post) | vs per-item 90th-pct rule | vs 28-day-average rule |",
          "|---|---|---|---|---|---|---|"]
    for k, m in dec["policies"].items():
        ci, ci2 = m.get("stock_saving_vs_rule_ex_post_ci"), m.get("stock_saving_vs_28day_rule_ex_post_ci")
        L.append(f"| {k} | {m['wape_of_weekly_totals']:.1%} | {m['fill_rate']:.1%} | {m['stock_vs_demand']:.2f} | {m['stock_vs_demand_at_95pct_fill_ex_post']:.2f} | "
                 f"{-m['stock_saving_vs_rule_ex_post']:+.1%}" + (f" (CI {-ci[1]:+.1%} to {-ci[0]:+.1%})" if ci else "") + " | "
                 f"{-m['stock_saving_vs_28day_rule_ex_post']:+.1%}" + (f" (CI {-ci2[1]:+.1%} to {-ci2[0]:+.1%})" if ci2 else "") + " |")
    L += ["", "Negative = less stock than the rule for the same 95% fill rate. Stock / demand and fill rate use the scale factor fixed before the test."]
    L += ["", f"## Explanation (exact TreeSHAP, {ex['model']}, {ex['n_rows']} test rows, additivity error {ex['additivity_max_error']:.1e})", "",
          "Mean |SHAP|: " + ", ".join(f"{LABELS.get(k, k)} {v:.3f}" for k, v in list(ex["mean_abs_shap"].items())[:8]) + ".", "",
          "## Hypothesis tests (Holm-corrected)", "", "| # | Hypothesis | Evidence | p (Holm) | Verdict |", "|---|---|---|---|---|"]
    for h in hyp:
        L.append(f"| {h['id']} | {h['hypothesis']} | {h['evidence']} | {h['p_holm']:.2g} | {h['verdict']} |")
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=config.TCS_RESULTS)
    ap.add_argument("--reports", type=Path, default=config.REPORTS_DIR)
    a = ap.parse_args(argv)
    figures(a.results, a.reports / "figures")
    (a.reports / "tcs.md").write_text(markdown(a.results))


if __name__ == "__main__":
    main()
